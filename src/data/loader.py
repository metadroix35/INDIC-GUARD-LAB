def load_or_create_dataset(
    filepath: Optional[Path] = None,
    save_sample: bool = True,
) -> pd.DataFrame:
    """
    Load dataset from path if available, or generate and save benchmark sample dataset.
    """
    if filepath and filepath.exists():
        logger.info(f"Loading dataset from {filepath}")
        if filepath.suffix.lower() == ".csv":
            return pd.read_csv(filepath)
        elif filepath.suffix.lower() == ".json":
            return pd.read_json(filepath)
        else:
            raise ValueError(f"Unsupported file format: {filepath.suffix}")

    # Fallback to generating sample benchmark
    sample_file = SAMPLE_DATA_DIR / "sample_multilingual_benchmark.csv"
    if sample_file.exists():
        logger.info(f"Loading existing sample benchmark from {sample_file}")
        return pd.read_csv(sample_file)

    logger.info("Generating standard multilingual benchmark dataset...")
    df = generate_benchmark_dataset()
    if save_sample:
        SAMPLE_DATA_DIR.mkdir(parents=True, exist_ok=True)
        df.to_csv(sample_file, index=False, encoding="utf-8")
        logger.info(f"Saved benchmark dataset to {sample_file}")
    return df
